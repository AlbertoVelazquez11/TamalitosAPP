const SVG_OPEN = (size) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
  `viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
  `stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">`;

/**
 * Devuelve un icono SVG inline como string.
 * @param {string} name — clave del icono (p. ej. 'trash', 'check')
 * @param {number} [size=20] — ancho/alto en píxeles
 * @returns {string} SVG embebible, o '' si el nombre es desconocido
 */
export function icon(name, size = 20) {
  const inner = ICONS[name];
  if (!inner) return '';
  return `${SVG_OPEN(size)}${inner}</svg>`;
}
